def clean_up_cds(input_string):
    """
    Normalize a comma-delimited string by trimming whitespace.
    Removes leading & trailing spaces from each element in a comma-delimited string.

    Parameters
    ----------
    input_string : str or None
        Input string with comma-delimited tokens, or None.

    Returns
    -------
    str
        A comma-joined string with each token stripped of leading/trailing
        whitespace. Returns '' if `input_string` is None.
    """
    # Split the string by commas
    if input_string is not None:
        items = input_string.split(',')                # put sting elements in a list
        item_list = [item.strip() for item in items]   # Strip whitespace from each item, store in a list
        cleaned_string = ','.join(item_list)           # put it back into a string
    else:
        cleaned_string = ''
    return cleaned_string


def to_bool(value):
    """
    Best-effort conversion of various truthy/falsey forms to bool.

    Notes
    -----
    `bool("False")` is True in Python because non-empty strings are truthy.
    This helper interprets common string forms instead.

    Behaviors
    ---------
    Makes False, 0, No, etc. become actual boolean.
    bool() doesn’t convert strings like "False" the way you expect;  only checks if the string is empty or not.


    Parameters
    ----------
    value : Any
        Value to interpret as boolean. Strings like "true", "yes", "on", "1"
        (case-insensitive) are treated as True; "false", "no", "off", "0"
        are treated as False. Booleans are returned unchanged.

    Returns
    -------
    bool
        Interpreted boolean value.
    """
    if isinstance(value, bool):
        return value
    if isinstance(value, str):
        return value.strip().lower() in ("1", "true", "yes", "on")
    return bool(value)


